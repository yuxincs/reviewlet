func TestLevel(t *testing.T) {
	for _, level := range []string{"", "debug", "INFO", "warn", "error"} {
		if _, err := New(io.Discard, level); err != nil {
			t.Errorf("valid level %q: %v", level, err)
		}
	}
	if _, err := New(io.Discard, "invalid"); err == nil {
		t.Fatal("invalid log level accepted")
	}
	var output bytes.Buffer
	logger, err := New(&output, "warn")
	if err != nil {
		t.Fatal(err)
	}
	logger.Info("hidden")
	logger.Warn("visible")
	if strings.Contains(output.String(), "hidden") || !strings.Contains(output.String(), "visible") {
		t.Fatal("log level did not filter records")
	}
}

func TestRequestLogging(t *testing.T) {
	var output bytes.Buffer
	logger, err := New(&output, "")
	if err != nil {
		t.Fatal(err)
	}
	mux := http.NewServeMux()
	mux.HandleFunc("POST /api/v1/review", func(w http.ResponseWriter, r *http.Request) {
		FromContext(r.Context(), logger).InfoContext(r.Context(), "handler_event")
		w.WriteHeader(http.StatusCreated)
		w.WriteHeader(http.StatusInternalServerError)
		_, _ = io.WriteString(w, "ok")
	})
	request := httptest.NewRequest(http.MethodPost, "/api/v1/review?secret=query-secret", strings.NewReader("body-secret"))
	request.Header.Set("Authorization", "Bearer key-secret")
	request.Header.Set("X-Request-ID", "untrusted-id")
	response := httptest.NewRecorder()
	Middleware(logger, mux).ServeHTTP(response, request)
	id := response.Header().Get("X-Request-ID")
	if id == "" || id == "untrusted-id" {
		t.Fatal("request ID was not generated by server")
	}
	records := strings.Split(strings.TrimSpace(output.String()), "\n")
	if len(records) != 2 {
		t.Fatalf("expected correlated handler and access records: %s", output.String())
	}
	for _, line := range records {
		var record map[string]any
		if err := json.Unmarshal([]byte(line), &record); err != nil {
			t.Fatal(err)
		}
		if record["request_id"] != id || record["service"] != "reviewlet-backend" {
			t.Fatal("request context was not propagated")
		}
		if record["msg"] == "http_request_completed" {
			if record["status"] != float64(201) || record["response_bytes"] != float64(2) || record["route"] != "POST /api/v1/review" || record["duration_ms"] == nil {
				t.Fatalf("incorrect access log: %+v", record)
			}
		}
	}
	for _, secret := range []string{"query-secret", "body-secret", "key-secret", "untrusted-id"} {
		if strings.Contains(output.String(), secret) {
			t.Fatalf("logged sensitive data: %s", secret)
		}
	}
}

func TestUnknownRoutesAndRequestLevels(t *testing.T) {
	for _, status := range []int{200, 400, 500} {
		var output bytes.Buffer
		logger, _ := New(&output, "")
		handler := http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) { w.WriteHeader(status) })
		response := httptest.NewRecorder()
		Middleware(logger, handler).ServeHTTP(response, httptest.NewRequest(http.MethodGet, "/path-secret?q=query-secret", nil))
		var record map[string]any
		if err := json.Unmarshal(output.Bytes(), &record); err != nil {
			t.Fatal(err)
		}
		expected := map[int]string{200: "INFO", 400: "WARN", 500: "ERROR"}[status]
		if record["route"] != "unmatched" || record["level"] != expected {
			t.Fatalf("unexpected log record: %+v", record)
		}
		if strings.Contains(output.String(), "secret") {
			t.Fatal("unmatched URL leaked")
		}
	}
}

func TestResponseControllerUnwrap(t *testing.T) {
	underlying := httptest.NewRecorder()
	writer := &responseWriter{ResponseWriter: underlying}
	if writer.Unwrap() != underlying {
		t.Fatal("response writer cannot be unwrapped")
	}
	if err := http.NewResponseController(writer).Flush(); err != nil {
		t.Fatal(err)
	}
}
