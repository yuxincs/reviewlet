// Command apischema extracts runtime JSON schemas from the OpenAPI contract.
package main

import (
	"encoding/json"
	"fmt"
	"os"

	"go.yaml.in/yaml/v3"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	if len(os.Args) != 3 {
		return fmt.Errorf("usage: apischema input.yaml output.json")
	}
	source, err := os.ReadFile(os.Args[1])
	if err != nil {
		return err
	}
	var spec struct {
		Components struct {
			Schemas map[string]any `yaml:"schemas"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(source, &spec); err != nil {
		return err
	}
	response, ok := spec.Components.Schemas["ReviewResponse"].(map[string]any)
	if !ok {
		return fmt.Errorf("ReviewResponse schema is missing")
	}
	properties, ok := response["properties"].(map[string]any)
	if !ok {
		return fmt.Errorf("ReviewResponse properties are missing")
	}
	// Metadata belongs to the service; only these fields are generated by the LLM.
	modelProperties := map[string]any{}
	for _, key := range []string{"language", "summary", "findings"} {
		if properties[key] == nil {
			return fmt.Errorf("ReviewResponse.%s is missing", key)
		}
		modelProperties[key] = properties[key]
	}
	spec.Components.Schemas["ModelReview"] = map[string]any{
		"type": "object", "additionalProperties": false,
		"required": []string{"language", "summary", "findings"}, "properties": modelProperties,
	}
	output, err := json.MarshalIndent(map[string]any{
		"$schema":    "https://json-schema.org/draft/2020-12/schema",
		"components": map[string]any{"schemas": spec.Components.Schemas},
	}, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(os.Args[2], append(output, '\n'), 0o600)
}
